#!/usr/bin/env node
/**
 * Merge per-screen SCREEN_OVERRIDES + PRIMITIVE_OVERRIDES → overrides.generated.ts
 * Collision detection: duplicate component_id across files → exit 1
 * Run: node scripts/w2-merge-overrides.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { keysInOverrideFile, overridesDir } from "./w2-override-keys.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OVERRIDES_DIR = overridesDir(ROOT);
const OUT_FILE = path.join(ROOT, "packages/ihl-ui-catalog/src/registry/overrides.generated.ts");

const SKIP = new Set(["primitives.ts"]);

function safeVarName(fileName) {
  return fileName
    .replace(/\.ts$/, "")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^(\d)/, "_$1");
}

function listScreenFiles() {
  if (!fs.existsSync(OVERRIDES_DIR)) {
    console.error(`Missing overrides dir: ${OVERRIDES_DIR}`);
    process.exit(1);
  }
  return fs
    .readdirSync(OVERRIDES_DIR)
    .filter((f) => f.endsWith(".ts") && !SKIP.has(f))
    .sort();
}

function countKeysInFile(relPath) {
  return keysInOverrideFile(ROOT, relPath);
}

function detectCollisions(screenFiles) {
  const owner = new Map();
  const collisions = [];

  for (const file of ["primitives.ts", ...screenFiles]) {
    const rel = file;
    const keys = file === "primitives.ts" ? countKeysInFile("primitives.ts") : countKeysInFile(rel);
    for (const key of keys) {
      if (owner.has(key)) {
        collisions.push({ key, a: owner.get(key), b: rel });
      } else {
        owner.set(key, rel);
      }
    }
  }

  return collisions;
}

function generate(screenFiles) {
  const importLines = [`import { PRIMITIVE_OVERRIDES } from "./overrides/primitives";`];
  const spreadLines = ["  ...PRIMITIVE_OVERRIDES,"];

  for (const file of screenFiles) {
    const varName = safeVarName(file) + "_OVERRIDES";
    const base = file.replace(/\.ts$/, "");
    importLines.push(`import { SCREEN_OVERRIDES as ${varName} } from "./overrides/${base}";`);
    spreadLines.push(`  ...${varName},`);
  }

  return `/* AUTO-GENERATED by scripts/w2-merge-overrides.mjs — do not edit */
${importLines.join("\n")}
import type { CatalogComponent } from "./overrides.types";

/** Merged hand overrides — per-screen files + primitives */
export const COMPONENT_OVERRIDES: Record<string, CatalogComponent> = {
${spreadLines.join("\n")}
};
`;
}

// --- main ---
const screenFiles = listScreenFiles();
const collisions = detectCollisions(screenFiles);

if (collisions.length > 0) {
  console.error("COLLISION — duplicate component_id across override files:");
  for (const c of collisions) {
    console.error(`  ${c.key}: ${c.a} vs ${c.b}`);
  }
  process.exit(1);
}

const output = generate(screenFiles);
fs.writeFileSync(OUT_FILE, output);

const primitiveKeys = countKeysInFile("primitives.ts").length;
const screenKeyCount = screenFiles.reduce((n, f) => n + countKeysInFile(f).length, 0);
console.log(
  `Merged ${screenFiles.length} screen files + primitives → ${OUT_FILE}`,
);
console.log(`  ${primitiveKeys} primitive keys + ${screenKeyCount} screen keys = ${primitiveKeys + screenKeyCount} total`);
